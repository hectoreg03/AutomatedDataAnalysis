    def analisis_correlaciones(self):
        """Punto 4.5 del PDF: Matriz Pearson y Top 5 correlaciones"""
        print("🔗 Analizando Correlaciones...")
        num_df = self.df.select_dtypes(include=np.number)

        if num_df.shape[1] < 2:
            return

        corr_matrix = num_df.corr(method='pearson')

        plt.figure(figsize=(10, 8))
        sns.heatmap(corr_matrix, cmap="coolwarm", annot=True, fmt=".2f")
        plt.title("Matriz de Correlación (Pearson)")
        self._guardar_grafico("heatmap_correlacion")

        corr_unstack = corr_matrix.abs().unstack()
        so = corr_unstack.sort_values(ascending=False)
        so = so[so < 1.0]
        top_corr = so.head(10)

        unique_corrs = []
        seen = set()
        for idx, val in top_corr.items():
            pair = tuple(sorted(idx))
            if pair not in seen:
                seen.add(pair)
                real_val = corr_matrix.loc[idx[0], idx[1]]
                unique_corrs.append(f"{idx[0]} vs {idx[1]}: {real_val:.2f}")
                if len(unique_corrs) == 5:
                    break

        self.resumen_tecnico["top_correlaciones"] = unique_corrs
        print("   Top 5 correlaciones identificadas.")

        # Descripción dinámica Correlación
        if unique_corrs:
            top_pair = unique_corrs[0] # ej "Age vs Salary: 0.85"
            desc_corr = (f"Matriz de coeficientes de Pearson. Los colores rojos intensos indican correlación positiva fuerte y los azules negativa. "
                         f"La relación más significativa encontrada es {top_pair}, lo que sugiere una fuerte dependencia lineal entre estas variables.")
        else:
            desc_corr = "Matriz de correlación de Pearson. No se detectaron correlaciones lineales significativas entre las variables numéricas."

        self.graficos_descripciones["heatmap_correlacion.png"] = desc_corr

