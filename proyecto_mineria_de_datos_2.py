    def analisis_estadistico(self):
        """Punto 4.3 del PDF: Análisis Estadístico (Frecuencias, Moda, Nulos)"""
        print("⚡ Ejecutando Análisis Estadístico...")

        total_celdas = np.prod(self.df.shape)
        total_nulos = self.df.isnull().sum().sum()
        promedio_nulos = (total_nulos / total_celdas) * 100
        self.resumen_tecnico["promedio_valores_faltantes"] = f"{promedio_nulos:.2f}%"

        cat_cols = self.df.select_dtypes(include=['object', 'category']).columns
        for col in cat_cols:
            if not self.df[col].mode().empty:
                moda = self.df[col].mode()[0]
            else:
                moda = "N/A"

            if not self.df[col].value_counts().empty:
                top_freq = self.df[col].value_counts().iloc[0]
            else:
                top_freq = 0

            self.resumen_tecnico["insights_extra"].append(
                f"Columna '{col}': La moda es '{moda}' apareciendo {top_freq} veces."
            )

    def detectar_outliers(self):
        """Parte del Punto 4.6: Calcular Total de Outliers"""
        print("🧮 Detectando Outliers (Método IQR)...")
        num_cols = self.df.select_dtypes(include=np.number).columns
        total_outliers = 0

        for col in num_cols:
            Q1 = self.df[col].quantile(0.25)
            Q3 = self.df[col].quantile(0.75)
            IQR = Q3 - Q1
            lower_bound = Q1 - 1.5 * IQR
            upper_bound = Q3 + 1.5 * IQR

            outliers_col = ((self.df[col] < lower_bound) | (self.df[col] > upper_bound)).sum()
            total_outliers += outliers_col

        self.resumen_tecnico["total_outliers"] = int(total_outliers)
        print(f"   Total de outliers detectados en todo el dataset: {total_outliers}")

